package main

import (
	"flag"
	"fmt"
	"image"
	"image/png"
	"math"
	"os"
	"strings"
)

func main() {
	in := flag.String("in", "../../../assets/truf.png", "logo PNG with an alpha channel")
	out := flag.String("out", "large_gen.go", "generated Go file")
	cols := flag.Int("cols", 30, "width of the mark in terminal columns")
	rows := flag.Int("rows", 11, "height of the mark in terminal rows")
	threshold := flag.Float64("threshold", 0.2, "ink coverage a 1x1 dot needs to be set")
	flag.Parse()

	img, err := readPNG(*in)
	if err != nil {
		fail(err)
	}
	lines := render(img, *cols, *rows, *threshold)

	var sb strings.Builder
	sb.WriteString("// Code generated by go run ./gen; DO NOT EDIT.\n\npackage marks\n\nconst Large = `")
	sb.WriteString(strings.Join(lines, "\n"))
	sb.WriteString("`\n")
	if err := os.WriteFile(*out, []byte(sb.String()), 0o644); err != nil {
		fail(err)
	}
}

func readPNG(path string) (image.Image, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	return png.Decode(f)
}

func ink(img image.Image, x, y int) bool {
	_, _, _, a := img.At(x, y).RGBA()
	return a > 0x4000
}

func bounds(img image.Image) image.Rectangle {
	b := img.Bounds()
	r := image.Rectangle{Min: b.Max, Max: b.Min}
	for y := b.Min.Y; y < b.Max.Y; y++ {
		for x := b.Min.X; x < b.Max.X; x++ {
			if ink(img, x, y) {
				r.Min.X = min(r.Min.X, x)
				r.Min.Y = min(r.Min.Y, y)
				r.Max.X = max(r.Max.X, x+1)
				r.Max.Y = max(r.Max.Y, y+1)
			}
		}
	}
	if r.Empty() {
		return b
	}
	return r
}

func render(img image.Image, cols, rows int, threshold float64) []string {
	box := bounds(img)
	dotsW, dotsH := cols*2, rows*4
	scale := math.Min(float64(dotsW)/float64(box.Dx()), float64(dotsH)/float64(box.Dy()))
	markW := int(math.Round(float64(box.Dx()) * scale))
	markH := int(math.Round(float64(box.Dy()) * scale))
	offX := (dotsW - markW) / 2
	offY := (dotsH - markH) / 2

	dot := func(dx, dy int) bool {
		dx -= offX
		dy -= offY
		if dx < 0 || dy < 0 || dx >= markW || dy >= markH {
			return false
		}
		x0 := box.Min.X + int(float64(dx)/scale)
		x1 := box.Min.X + int(float64(dx+1)/scale)
		y0 := box.Min.Y + int(float64(dy)/scale)
		y1 := box.Min.Y + int(float64(dy+1)/scale)
		total, hit := 0, 0
		for y := y0; y < max(y1, y0+1); y++ {
			for x := x0; x < max(x1, x0+1); x++ {
				total++
				if ink(img, x, y) {
					hit++
				}
			}
		}
		return float64(hit)/float64(total) >= threshold
	}

	bits := [4][2]rune{{0x01, 0x08}, {0x02, 0x10}, {0x04, 0x20}, {0x40, 0x80}}
	lines := make([]string, rows)
	for row := 0; row < rows; row++ {
		var sb strings.Builder
		for col := 0; col < cols; col++ {
			var r rune
			for sy := 0; sy < 4; sy++ {
				for sx := 0; sx < 2; sx++ {
					if dot(col*2+sx, row*4+sy) {
						r |= bits[sy][sx]
					}
				}
			}
			if r == 0 {
				sb.WriteRune(' ')
			} else {
				sb.WriteRune(0x2800 + r)
			}
		}
		lines[row] = strings.TrimRight(sb.String(), " ")
	}
	return lines
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "gen:", err)
	os.Exit(1)
}
